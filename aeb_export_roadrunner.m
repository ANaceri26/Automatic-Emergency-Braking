function folder=aeb_export_roadrunner(r,folder)
% Export lightweight replay data. Does not need RoadRunner to create files.
% This is recorded trajectory playback, NOT live RoadRunner co-simulation.
if nargin<1, r=aeb_simulate(aeb_config); end
root=fileparts(mfilename('fullpath'));
if nargin<2, folder=fullfile(root,'roadrunner',r.config.name); end
if ~exist(folder,'dir'), mkdir(folder); end
N=numel(r.time); zerosN=zeros(N,1);
% Preserve every simulation sample, including stationary segments and timing.
% World frame: +X forward, +Y left, +Z up. Vehicle centres at y=-1.75.
for actor=1:2
    index=1; name='ego.csv'; if actor==2, index=3; name='lead.csv'; end
    trajectory=table(r.time,r.state(:,index),-1.75*ones(N,1),zerosN,...
        zerosN,zerosN,zerosN,'VariableNames',{'time','x','y','z','yaw','pitch','roll'});
    writetable(trajectory,fullfile(folder,name));
end
% Simple OpenDRIVE 1.4 road; no scenery or heavy assets. Lane -1 follows +X.
roadLength=max(300,ceil(max(r.state(:,3))+100));
xodr=sprintf(['<?xml version="1.0" encoding="UTF-8"?>\n' ...
 '<OpenDRIVE>\n<header revMajor="1" revMinor="4" name="AEB straight road" version="1.0" date="2026-10-05" north="3.5" south="-3.5" east="%.3f" west="-50"/>\n' ...
 '<road name="AEB test road" length="%.3f" id="1" junction="-1">\n' ...
 '<link/><type s="0" type="rural"><speed max="25" unit="m/s"/></type>\n' ...
 '<planView><geometry s="0" x="-50" y="0" hdg="0" length="%.3f"><line/></geometry></planView>\n' ...
 '<elevationProfile><elevation s="0" a="0" b="0" c="0" d="0"/></elevationProfile>\n' ...
 '<lateralProfile/><lanes><laneOffset s="0" a="0" b="0" c="0" d="0"/>\n' ...
 '<laneSection s="0"><left><lane id="1" type="driving" level="false"><link/>' ...
 '<width sOffset="0" a="3.5" b="0" c="0" d="0"/>' ...
 '<roadMark sOffset="0" type="solid" weight="standard" color="white" width="0.12" laneChange="none"/>' ...
 '</lane></left><center><lane id="0" type="none" level="false"><link/>' ...
 '<roadMark sOffset="0" type="broken" weight="standard" color="yellow" width="0.12" laneChange="both"/>' ...
 '</lane></center><right><lane id="-1" type="driving" level="false"><link/>' ...
 '<width sOffset="0" a="3.5" b="0" c="0" d="0"/>' ...
 '<roadMark sOffset="0" type="solid" weight="standard" color="white" width="0.12" laneChange="none"/>' ...
 '</lane></right></laneSection></lanes></road></OpenDRIVE>\n'],...
 roadLength-50,roadLength,roadLength);
writeText(fullfile(folder,'straight_road.xodr'),xodr);
writeText(fullfile(folder,'replay_info.txt'),sprintf(...
 ['AEB Lab - RoadRunner replay\nCase: %s\nMATLAB: %s\n' ...
 'Duration: %.3f s\nVehicle length in physics: %.2f m\n' ...
 'CSV position reference: vehicle geometric centre. Yaw: radians.\n' ...
 'Check imported actor origin/dimensions; visual contact may differ from the MATLAB bumper-gap metric.\n' ...
 'This is prerecorded playback, not live controller execution.\n' ...
 'Import the road, then import both CSVs in Scenario Editing mode.\n' ...
 'See ../../ROADRUNNER_README.md.\n'],...
 r.config.name,version('-release'),r.time(end),r.config.carLength));
fprintf('RoadRunner replay files: %s\n',folder);
end
function writeText(path,content)
f=fopen(path,'w'); assert(f>=0,'AEB:Write','Cannot write %s',path);
clean=onCleanup(@()fclose(f)); fprintf(f,'%s',content);
end
